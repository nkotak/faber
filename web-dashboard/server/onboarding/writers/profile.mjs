// Validation block
// ---------------------------------------------------------------------------
if (import.meta.url === `file://${process.argv[1]}`) {
  const failures = [];
  let totalTests = 0;
  const fs = await import('node:fs/promises');
  const tmpRoot = `/tmp/onboarding-profile-validate-${Date.now()}`;
  await fs.mkdir(tmpRoot, { recursive: true });

  const payload = {
    candidate: {
      full_name: 'Jane Doe',
      email: 'jane@example.com',
      phone: '+1-555-0123',
      location: 'NYC',
      linkedin: 'linkedin.com/in/janedoe',
      portfolio_url: '',
      github: 'github.com/janedoe',
      twitter: '',
    },
    target_roles: {
      primary: ['Senior PM'],
      archetypes: [{ name: 'PM', level: 'Senior', fit: 'primary' }],
    },
    narrative: {
      headline: 'h',
      exit_story: 'e',
      superpowers: ['a', 'b', 'c'],
      proof_points: [],
    },
    compensation: {
      target_range: '$150K',
      currency: 'USD',
      minimum: '$120K',
      location_flexibility: '',
    },
    location: {
      country: 'US',
      city: 'NYC',
      timezone: 'EST',
      visa_status: '',
    },
  };

  // Test 1: writeProfileYaml writes valid YAML.
  totalTests += 1;
  try {
    const r = await writeProfileYaml(tmpRoot, payload);
    const text = await fs.readFile(r.path, 'utf-8');
    if (!text.includes('full_name: Jane Doe')) failures.push('YAML missing full_name');
    if (text.includes('twitter:')) failures.push('YAML should drop empty twitter');
    if (text.includes('proof_points')) failures.push('YAML should drop empty proof_points');
  } catch (err) {
    failures.push(`writeProfileYaml threw: ${err.message}`);
  }

  // Test 2: round-trip the YAML cleanly.
  totalTests += 1;
  try {
    const text = await fs.readFile(path.join(tmpRoot, 'config', 'profile.yml'), 'utf-8');
    const parsed = YAML.parse(text);
    if (parsed.candidate.email !== 'jane@example.com') failures.push('round-trip lost email');
    if (parsed.target_roles.archetypes[0].fit !== 'primary') failures.push('round-trip lost fit');
  } catch (err) {
    failures.push(`round-trip threw: ${err.message}`);
  }

  await fs.rm(tmpRoot, { recursive: true, force: true });

  if (failures.length > 0) {
    console.error(`VALIDATION FAILED - ${failures.length} of ${totalTests} tests failed:`);
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  } else {
    console.log(`VALIDATION PASSED - All ${totalTests} tests produced expected results`);
    process.exit(0);
  }
}
