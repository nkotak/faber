if (import.meta.url === `file://${process.argv[1]}`) {
  const failures = [];
  let totalTests = 0;
  const fs = await import('node:fs/promises');
  const path = await import('node:path');
  const { fileURLToPath } = await import('node:url');
  const tmpRoot = `/tmp/onboarding-portals-validate-${Date.now()}`;
  await fs.mkdir(path.join(tmpRoot, 'templates'), { recursive: true });

  // Resolve the real template relative to this script (project root is 4 levels up
  // from web-dashboard/server/onboarding/writers/).
  const __dirname = path.dirname(fileURLToPath(import.meta.url));
  const realTemplate = path.resolve(__dirname, '..', '..', '..', '..', 'templates', 'portals.example.yml');
  const tmpl = await fs.readFile(realTemplate, 'utf-8');
  await fs.writeFile(path.join(tmpRoot, 'templates', 'portals.example.yml'), tmpl);

  // Test 1: use_defaults preserves the original tracked_companies count.
  totalTests += 1;
  try {
    const r = await writePortalsYaml(tmpRoot, { use_defaults: true });
    const onDisk = await fs.readFile(r.path, 'utf-8');
    const parsed = YAML.parse(onDisk);
    if (!Array.isArray(parsed.tracked_companies) || parsed.tracked_companies.length === 0) {
      failures.push('use_defaults: tracked_companies missing');
    }
  } catch (err) {
    failures.push(`use_defaults threw: ${err.message}`);
  }

  // Test 2: custom title_filter overwrites positive list.
  totalTests += 1;
  try {
    const r = await writePortalsYaml(tmpRoot, {
      use_defaults: false,
      title_filter: { positive: ['Backend Engineer', 'Platform Engineer'], negative: ['Junior'] },
      companies: [],
    });
    const parsed = YAML.parse(await fs.readFile(r.path, 'utf-8'));
    if (parsed.title_filter.positive[0] !== 'Backend Engineer') failures.push('title_filter not applied');
    if (parsed.title_filter.negative[0] !== 'Junior') failures.push('negative not applied');
  } catch (err) {
    failures.push(`custom title_filter threw: ${err.message}`);
  }

  // Test 3: company toggles flip enabled flags.
  totalTests += 1;
  try {
    const r = await writePortalsYaml(tmpRoot, {
      use_defaults: false,
      companies: [{ name: 'Anthropic', enabled: false }, { name: 'OpenAI', enabled: false }],
    });
    const parsed = YAML.parse(await fs.readFile(r.path, 'utf-8'));
    const anthropic = parsed.tracked_companies.find((c) => c.name === 'Anthropic');
    const openai = parsed.tracked_companies.find((c) => c.name === 'OpenAI');
    if (!anthropic || anthropic.enabled !== false) failures.push('Anthropic enabled flag not flipped');
    if (!openai || openai.enabled !== false) failures.push('OpenAI enabled flag not flipped');
  } catch (err) {
    failures.push(`company toggles threw: ${err.message}`);
  }

  await fs.rm(tmpRoot, { recursive: true, force: true });

  if (failures.length > 0) {
    console.error(`VALIDATION FAILED - ${failures.length} of ${totalTests} tests failed:`);
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  } else {
    console.log(`VALIDATION PASSED - All ${totalTests} tests produced expected results`);
    process.exit(0);
  }
}
